#!/usr/bin/env node
// The dispatcher's bookkeeping, one command each (dispatcher SKILL.md; ported from stella-rain/tasks#587).
//   node dispatch.cjs [--owner O] [--repo R] [--queue N] [--ignore-file PATH] [--dry-run] <command>
//     dispatched <issue> <task> <session>   the `dispatched` comment on the queue; approved|planned -> running
//     label <issue> <status>                one status: label, every other one removed
//     done <issue> <owner/repo#PR> [--route <issue>]   the DONE comment from the parsed PR body, labels off, closed
//     decision <DS-NNNN> <file>             the file, headed `**DS-NNNN · YYYY-MM-DD · Kade:**`, on the queue
// Owner: --owner or DISPATCH_OWNER (required). Repo: --repo, DISPATCH_REPO, else `tasks`. Queue: --queue or
// DISPATCH_QUEUE, required by dispatched and decision. Every GitHub call is `gh api repos/<owner>/<repo>/...`.
// Exit: 0 done, 1 a gh call failed (stdout lists what completed), 2 usage or refusal with nothing written,
// 3 done refused: the issue already has a DONE comment for that PR (stderr has its URL).
"use strict";

const fs = require("fs");
const os = require("os");
const path = require("path");
const { spawnSync } = require("child_process");
const { extract } = require("../../repo-workflow/scripts/pr-body.cjs");

const FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_";
const STATUSES = ["pending", "planned", "approved", "held", "running", "blocked"];
const PROTECTED = /\.claude\/rules\/|\.agents\/rules\/|\bAGENTS\.md|\bCLAUDE\.md|\.github\/workflows\//;
const DS_HEADER = /^\*\*DS-(\d{4}) · \d{4}-\d\d-\d\d · Kade:\*\*/; // decisions.yml logs only Kade's

class Fail extends Error {
  constructor(code, msg) { super(msg); this.code = code; }
}
const usage = (msg) => new Fail(2, msg);

function parseArgs(argv) {
  const flags = {};
  const pos = [];
  const valued = ["--owner", "--repo", "--queue", "--ignore-file", "--route"];
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--dry-run") flags.dryRun = true;
    else if (valued.includes(a)) {
      if (i + 1 >= argv.length) throw usage(`${a} needs a value`);
      flags[a.slice(2)] = argv[++i];
    } else if (a.startsWith("--")) throw usage(`unknown option ${a}`);
    else pos.push(a);
  }
  return { flags, pos };
}

const issueNumber = (s, what) => {
  if (!/^\d+$/.test(s || "")) throw usage(`${what} must be an issue number, got ${JSON.stringify(s)}`);
  return Number(s);
};

class Ctx {
  constructor(flags, io) {
    const env = io.env;
    this.io = io;
    this.owner = flags.owner || env.DISPATCH_OWNER;
    if (!this.owner) throw usage("no owner: pass --owner or set DISPATCH_OWNER");
    this.repo = flags.repo || env.DISPATCH_REPO || "tasks";
    this.queueRaw = flags.queue || env.DISPATCH_QUEUE;
    const home = env.HOME || os.homedir();
    this.ignore = flags["ignore-file"] || env.WATCH_IGNOREFILE || path.join(home, ".claude", "dispatcher", `ignore-${this.owner}`);
    this.dry = !!flags.dryRun;
    this.done = [];
  }
  get slug() { return `${this.owner}/${this.repo}`; }
  get queue() {
    if (!this.queueRaw) throw usage("no queue: pass --queue or set DISPATCH_QUEUE");
    return issueNumber(this.queueRaw, "the queue");
  }
  path(tail) { return `repos/${this.slug}/${tail}`; }

  gh(args, data) {
    const r = this.io.run("gh", args, data === undefined ? undefined : JSON.stringify(data));
    if (r.status !== 0) throw new Fail(1, `gh ${args.join(" ")}: ${(r.stderr || "").trim()}`);
    return (r.stdout || "").trim() ? JSON.parse(r.stdout) : {};
  }
  // A read always runs, also in a dry run; a paginated list comes back flat.
  read(p, paginate = false) {
    const out = this.gh(["api", ...(paginate ? ["--paginate", "--slurp"] : []), p]);
    return paginate ? [out].flat(Infinity) : out;
  }
  write(verb, p, data) {
    if (this.dry) {
      this.io.out(`would ${verb} ${p}`);
      if (data !== undefined) this.io.out(JSON.stringify(data, null, 2));
      return { html_url: "(dry run)" };
    }
    return this.gh(["api", "-X", verb, p, ...(data !== undefined ? ["--input", "-"] : [])], data);
  }
  note(text) {
    if (!this.dry) this.io.out(text);
    this.done.push(text);
  }
  comment(issuePath, body) {
    const r = this.write("POST", issuePath + "/comments", { body: body + FOOTER });
    this.note("commented " + (r.html_url || ""));
    return r;
  }
  logIgnore(kind, ref, label) {
    const line = `${new Date().toISOString().replace(/\.\d{3}Z$/, "Z")} ${kind} ${ref}${label ? " " + label : ""}`;
    if (this.dry) return this.io.out(`would append to ${this.ignore}: ${line}`);
    fs.mkdirSync(path.dirname(path.resolve(this.ignore)), { recursive: true });
    fs.appendFileSync(this.ignore, line + "\n");
    this.io.out("ignore: " + line);
  }
}

const statuses = (iss) => (iss.labels || []).map((l) => l.name).filter((n) => n.startsWith("status:")).sort();
const labelPath = (c, n, name) => c.path(`issues/${n}/labels`) + (name ? "/" + encodeURIComponent(name) : "");

function dropLabels(c, n, names) {
  for (const name of names) {
    c.write("DELETE", labelPath(c, n, name));
    c.note(`label ${name} removed`);
  }
}

function setStatus(c, n, next, have) {
  if (!have.includes(next)) {
    c.write("POST", labelPath(c, n), { labels: [next] });
    c.note(`label ${next} added`);
  }
  dropLabels(c, n, have.filter((h) => h !== next));
  c.logIgnore("label", `${c.slug}#${n}`, next);
}

function cmdDispatched(c, [issue, task, session]) {
  const n = issueNumber(issue, "issue");
  if (!task || !session) throw usage("dispatched <issue> <task> <session>");
  const queue = c.queue;
  const have = statuses(c.read(c.path(`issues/${n}`)));
  let swap;
  if (have.length === 1 && have[0] === "status:running") swap = false;
  else if (have.length && have.every((h) => h === "status:approved" || h === "status:planned")) swap = true;
  else throw usage(`#${n} has ${have.join(", ") || "no status label"}, not status:approved or status:planned`);
  c.comment(c.path(`issues/${queue}`), `dispatched ${task}: ${session}`);
  if (swap) setStatus(c, n, "status:running", have);
}

function cmdLabel(c, [issue, status]) {
  const n = issueNumber(issue, "issue");
  const s = (status || "").replace(/^status:/, "");
  if (!STATUSES.includes(s)) throw usage(`status must be one of ${STATUSES.join(", ")}`);
  const next = "status:" + s;
  const have = statuses(c.read(c.path(`issues/${n}`)));
  if (have.length === 1 && have[0] === next) return c.io.out("unchanged");
  setStatus(c, n, next, have);
}

function splitRef(ref) {
  const m = /^([\w.-]+)\/([\w.-]+)#(\d+)$/.exec(ref || "");
  if (!m) throw usage(`PR must look like <owner>/<repo>#<n>, got ${JSON.stringify(ref)}`);
  return [m[1], m[2], Number(m[3])];
}

// The DONE comment body, without the footer. routed: follow-up text -> the `owner/repo#N` it went to.
function doneText(task, ref, sha, title, ex, routed) {
  const out = [`DONE ${task}: merged as ${ref} (${sha.slice(0, 7)}): ${title}`];
  const block = (head, lines) => { if (lines.length) out.push(`**${head}**\n${lines.join("\n")}`); };
  block("Parse errors", ex.errors.map((e) => "- " + e));
  block("NOT VERIFIED", ex.notVerified.map((x) => `- ${x.gate}: ${x.reason}`));
  block("Kade's steps", ex.kadesSteps.map((x) => `- [${x.done ? "x" : " "}] ${x.text}`));
  block("Follow-ups", ex.followUps.map((f) => (routed.has(f) ? `- Routed to ${routed.get(f)}: ${f}` : "- " + f)));
  const ph = ex.placeholders;
  out.push(ph.length ? "**Placeholders**\n" + ph.map((x) => "- " + x).join("\n") : "**Placeholders:** none.");
  return out.join("\n\n");
}

function cmdDone(c, [issue, prRef], flags) {
  const n = issueNumber(issue, "issue");
  const route = flags.route === undefined ? null : issueNumber(flags.route, "--route");
  const [owner, repo, num] = splitRef(prRef);
  const ref = `${owner}/${repo}#${num}`;
  const pr = c.read(`repos/${owner}/${repo}/pulls/${num}`);
  if (!pr.merged) throw usage(`${ref} is not merged`);
  const iss = c.read(c.path(`issues/${n}`));
  const ex = extract(pr.body || "");
  let task = ex.task;
  if (!task) {
    const m = /<!-- task:(\S+?) -->/.exec(iss.body || "");
    task = m ? m[1] : null;
  }
  if (!task) throw usage("no task id: the PR body has no `Task:` line and the issue no <!-- task:ID --> marker");
  const doneRe = new RegExp(`^DONE \\S+: merged as ${ref.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")} \\(`);
  for (const cm of c.read(c.path(`issues/${n}/comments`), true)) {
    if (doneRe.test(cm.body || "")) throw new Fail(3, `#${n} already has a DONE comment for ${ref}: ${cm.html_url || ""}`);
  }
  const routed = new Map();
  if (route !== null) {
    for (const f of ex.followUps) if (PROTECTED.test(f)) routed.set(f, `${c.slug}#${route}`);
    if (routed.size) {
      c.comment(c.path(`issues/${route}`), `From ${task} (${ref}), follow-ups that name protected paths:\n\n` +
        [...routed.keys()].map((f) => "- " + f).join("\n"));
    }
  }
  c.comment(c.path(`issues/${n}`), doneText(task, ref, pr.merge_commit_sha || "", pr.title || "", ex, routed));
  dropLabels(c, n, statuses(iss));
  if (iss.state !== "closed") {
    c.write("PATCH", c.path(`issues/${n}`), { state: "closed", state_reason: "completed" });
    c.note("closed as completed");
    c.logIgnore("close", `${c.slug}#${n}`);
  }
}

function cmdDecision(c, [id, file]) {
  if (!id || !file) throw usage("decision <DS-NNNN> <file>");
  const queue = c.queue;
  let text;
  try { text = fs.readFileSync(file, "utf8"); } catch (e) { throw usage(`cannot read ${file}: ${e.message}`); }
  const first = text.split("\n").find((l) => l.trim()) || "";
  const m = DS_HEADER.exec(first);
  if (!m || "DS-" + m[1] !== id) {
    throw usage(`the first line must be \`**${id} · YYYY-MM-DD · Kade:**\`; it is ${JSON.stringify(first.slice(0, 80))}`);
  }
  let body = text.trimEnd();
  if (body.endsWith(FOOTER.trim())) body = body.slice(0, -FOOTER.trim().length).trimEnd();
  c.comment(c.path(`issues/${queue}`), body);
}

const COMMANDS = { dispatched: cmdDispatched, label: cmdLabel, done: cmdDone, decision: cmdDecision };

const defaultIo = {
  env: process.env,
  run: (cmd, args, input) => {
    const r = spawnSync(cmd, args, { input, encoding: "utf8", stdio: [input === undefined ? "ignore" : "pipe", "pipe", "pipe"] });
    return r.error ? { status: 1, stdout: "", stderr: r.error.message } : r;
  },
  out: (s) => process.stdout.write(s + "\n"),
  err: (s) => process.stderr.write(s + "\n"),
};

function main(argv, io = defaultIo) {
  let c;
  try {
    const { flags, pos } = parseArgs(argv);
    const [cmd, ...args] = pos;
    if (!COMMANDS[cmd]) throw usage(`command must be one of ${Object.keys(COMMANDS).join(", ")}`);
    c = new Ctx(flags, io);
    COMMANDS[cmd](c, args, flags);
    return 0;
  } catch (e) {
    if (!(e instanceof Fail)) throw e;
    io.err("error: " + e.message);
    if (e.code === 1 && c && c.done.length) io.out("completed before the failure: " + c.done.join("; "));
    return e.code;
  }
}

module.exports = { main, doneText };

if (require.main === module) process.exit(main(process.argv.slice(2)));
