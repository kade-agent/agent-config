// The dispatcher's bookkeeping, one command each (ported from stella-rain/tasks#587 so every org's
// dispatcher has it): gh is faked through the io.run hook, the ignore file is a temp file.
"use strict";

const test = require("node:test");
const assert = require("node:assert");
const fs = require("fs");
const os = require("os");
const path = require("path");

const SCRIPT = path.join(__dirname, "..", "agent-skills", "dispatcher", "scripts", "dispatch.cjs");
const { main } = require(SCRIPT);

const FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_";
const ISO = "\\d{4}-\\d\\d-\\d\\dT\\d\\d:\\d\\d:\\d\\dZ";
const Q = "repos/stella-rain/tasks/issues";
const ORG = ["--owner", "stella-rain", "--queue", "145"];

// Answers gh GETs from a map, records every call. fail: [verb, path suffix] pairs that exit 1.
function fakeGh(gets = {}, fail = []) {
  const calls = [];
  const run = (cmd, args, input) => {
    assert.strictEqual(cmd, "gh");
    assert.strictEqual(args[0], "api", args.join(" "));
    const p = args.find((a) => a.startsWith("repos/"));
    const verb = args.includes("-X") ? args[args.indexOf("-X") + 1] : "GET";
    calls.push({ verb, path: p, data: input ? JSON.parse(input) : null, args });
    if (fail.some(([v, s]) => v === verb && p.endsWith(s))) return { status: 1, stdout: "", stderr: "boom" };
    if (verb === "GET") {
      if (!(p in gets)) throw new Error("unscripted GET " + p);
      return { status: 0, stdout: JSON.stringify(gets[p]), stderr: "" };
    }
    if (verb === "POST" && p.endsWith("/comments")) {
      const n = calls.filter((c) => c.verb === "POST").length;
      return { status: 0, stdout: JSON.stringify({ html_url: `https://github.com/x/y/issues/1#c${n}` }), stderr: "" };
    }
    return { status: 0, stdout: "{}", stderr: "" };
  };
  run.calls = calls;
  run.writes = () => calls.filter((c) => c.verb !== "GET").map((c) => [c.verb, c.path, c.data]);
  return run;
}

const issue = (labels = [], { state = "open", body = "" } = {}) =>
  ({ labels: labels.map((name) => ({ name })), state, body });

function world() {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "dispatch-"));
  const home = path.join(tmp, "home");
  fs.mkdirSync(home);
  const ign = path.join(tmp, "ignore");
  const w = {
    tmp, home, ign,
    run(argv, gh, { env = {}, ignore = true } = {}) {
      let out = "", err = "";
      const io = { env: { HOME: home, ...env }, run: gh, out: (s) => { out += s + "\n"; }, err: (s) => { err += s + "\n"; } };
      const code = main([...(ignore ? ["--ignore-file", ign] : []), ...argv], io);
      w.out = out; w.err = err;
      return code;
    },
    ignoreLines: () => (fs.existsSync(ign) ? fs.readFileSync(ign, "utf8").split("\n").filter(Boolean) : []),
    file(text) {
      const p = path.join(tmp, "d.md");
      fs.writeFileSync(p, text);
      return p;
    },
  };
  return w;
}

const PR_BODY = (sections = {}) => [
  "Closes stella-rain/tasks#586", sections.task === null ? "Task: none" : `Task: ${sections.task || "T-1"}`, "",
  "## What changed and why", "x", "## Verified", "y",
  "## NOT VERIFIED", sections.nv || "None",
  "## Kade's steps", sections.steps || "None",
  "## Follow-ups", sections.follow || "None",
  "## Placeholders", sections.ph || "None",
  "## Wrong turns", "None"].join("\n");

const FULL = {
  nv: "- NOT VERIFIED: cargo bench: no runner",
  steps: "- [ ] merge it\n- [x] ran it",
  follow: "- rules text for .claude/rules/simulation.md and more\n- restore_removed_fields can go",
};

function doneGh({ body = PR_BODY(), merged = true, state = "open", issueBody = "", labels = ["status:running"],
  comments = [], sha = "681319e1234567890" } = {}) {
  return fakeGh({
    [Q + "/586"]: issue(labels, { state, body: issueBody }),
    [Q + "/586/comments"]: comments,
    "repos/stella-rain/core/pulls/652": { merged, title: "Fix the thing", body, merge_commit_sha: sha },
  });
}

const posts = (gh) => gh.writes().filter((x) => x[0] === "POST");

// --- configuration ---

test("owner and queue come from flags, else env; a flag wins", () => {
  const w = world();
  let gh = fakeGh({ "repos/o/r/issues/586": issue(["status:approved"]) });
  assert.strictEqual(w.run(["--owner", "o", "--repo", "r", "--queue", "9", "dispatched", "586", "T-1", "s"], gh), 0, w.err);
  assert.strictEqual(gh.calls[1].path, "repos/o/r/issues/9/comments");
  gh = fakeGh({ "repos/o/r/issues/586": issue(["status:approved"]) });
  w.run(["dispatched", "586", "T-1", "s"], gh, { env: { DISPATCH_OWNER: "o", DISPATCH_REPO: "r", DISPATCH_QUEUE: "9" } });
  assert.strictEqual(gh.calls[1].path, "repos/o/r/issues/9/comments");
  gh = fakeGh({ "repos/o2/tasks/issues/586": issue(["status:approved"]) });
  w.run(["--owner", "o2", "--queue", "9", "dispatched", "586", "T-1", "s"], gh, { env: { DISPATCH_OWNER: "o" } });
  assert.strictEqual(gh.calls[0].path, "repos/o2/tasks/issues/586");
});

test("no owner, or no queue for a command that posts on it, is exit 2 with nothing called", () => {
  const w = world();
  let gh = fakeGh();
  assert.strictEqual(w.run(["--queue", "145", "label", "586", "held"], gh), 2);
  assert.match(w.err, /owner/);
  assert.deepStrictEqual(gh.calls, []);
  gh = fakeGh();
  assert.strictEqual(w.run(["--owner", "stella-rain", "dispatched", "586", "T-1", "s"], gh), 2);
  assert.match(w.err, /queue/);
  assert.deepStrictEqual(gh.calls, []);
  gh = fakeGh({ [Q + "/586"]: issue(["status:approved"]) });
  assert.strictEqual(w.run(["--owner", "stella-rain", "label", "586", "held"], gh), 0, "label needs no queue");
});

test("a queue that is not an issue number is exit 2 with nothing called (#587: DISPATCH_QUEUE=abc)", () => {
  for (const [argv, env] of [[["--queue", "abc"], {}], [[], { DISPATCH_QUEUE: "abc" }], [["--queue", "0x9"], {}]]) {
    const w = world();
    const gh = fakeGh({ [Q + "/586"]: issue(["status:approved"]) });
    assert.strictEqual(w.run(["--owner", "stella-rain", ...argv, "dispatched", "586", "T-1", "s"], gh, { env }), 2, argv.join(" "));
    assert.match(w.err, /queue/);
    assert.deepStrictEqual(gh.calls, []);
  }
});

test("the ignore file defaults to ~/.claude/dispatcher/ignore-<owner>; WATCH_IGNOREFILE overrides it", () => {
  const w = world();
  w.run([...ORG, "dispatched", "586", "T-1", "s"], fakeGh({ [Q + "/586"]: issue(["status:approved"]) }), { ignore: false });
  assert.ok(fs.existsSync(path.join(w.home, ".claude", "dispatcher", "ignore-stella-rain")));
  const other = path.join(w.tmp, "w", "ign");
  w.run([...ORG, "dispatched", "586", "T-1", "s"], fakeGh({ [Q + "/586"]: issue(["status:approved"]) }),
    { env: { WATCH_IGNOREFILE: other }, ignore: false });
  assert.ok(fs.existsSync(other));
});

