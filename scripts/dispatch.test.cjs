test("done --route: follow-ups naming protected paths go to the route issue first", () => {
  const w = world();
  const gh = doneGh({ body: PR_BODY(FULL) });
  assert.strictEqual(done(w, gh, "--route", "574"), 0, w.err);
  const [first, second] = gh.writes();
  assert.strictEqual(first[1], Q + "/574/comments");
  assert.strictEqual(first[2].body, "From T-1 (stella-rain/core#652), follow-ups that name protected paths:\n\n" +
    "- rules text for .claude/rules/simulation.md and more" + FOOTER);
  assert.strictEqual(second[1], Q + "/586/comments");
  assert.ok(second[2].body.includes("- Routed to stella-rain/tasks#574: rules text for"));
  assert.ok(second[2].body.includes("\n- restore_removed_fields can go"));
});

test("done without --route posts one comment; each protected path triggers a route", () => {
  const w = world();
  let gh = doneGh({ body: PR_BODY(FULL) });
  done(w, gh);
  assert.strictEqual(posts(gh).length, 1);
  assert.ok(!posts(gh)[0][2].body.includes("Routed"));
  for (const [text, routed] of [["see .agents/rules/x.md", true], ["edit AGENTS.md", true], ["edit CLAUDE.md", true],
    ["change .github/workflows/a.yml", true], ["the agents help", false]]) {
    gh = doneGh({ body: PR_BODY({ follow: "- " + text }) });
    done(w, gh, "--route", "574");
    assert.strictEqual(posts(gh).length === 2, routed, text);
  }
});

test("done: a second DONE for the same PR is exit 3 with the comment's URL, before any write", () => {
  const URL = "https://github.com/stella-rain/tasks/issues/586#issuecomment-77";
  const old = (ref) => [{ body: "dispatched T-1: s", html_url: "https://x/1" },
    { body: `DONE T-1: merged as ${ref} (681319e): Fix the thing\n\n**Placeholders:** none.` + FOOTER, html_url: URL }];
  const w = world();
  let gh = doneGh({ body: PR_BODY(FULL), comments: old("stella-rain/core#652") });
  assert.strictEqual(done(w, gh, "--route", "574"), 3);
  assert.ok(w.err.includes(URL));
  assert.deepStrictEqual(gh.writes(), []);
  assert.deepStrictEqual(w.ignoreLines(), []);
  for (const other of ["stella-rain/core#65", "stella-rain/core#6520", "stella-rain/app#652"]) {
    gh = doneGh({ comments: old(other) });
    assert.strictEqual(done(w, gh), 0, other);
  }
  gh = doneGh({ comments: [[{ body: "x", html_url: "u" }], old("stella-rain/core#652")] });
  assert.strictEqual(done(w, gh), 3, "paginated pages are flattened");
  gh = doneGh({ comments: old("stella-rain/core#652") });
  assert.strictEqual(w.run(["--dry-run", ...ORG, "done", "586", "stella-rain/core#652"], gh), 3, "the guard holds in a dry run");
  const get = gh.calls.find((c) => c.path.endsWith("/comments"));
  assert.ok(get.args.includes("--paginate") && get.args.includes("--slurp"));
});

