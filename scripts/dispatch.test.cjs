// --- done ---

const done = (w, gh, ...extra) => w.run([...ORG, "done", "586", "stella-rain/core#652", ...extra], gh);

test("done: the DONE comment from the parsed body, then the labels removed and the issue closed", () => {
  const w = world();
  const gh = doneGh({ body: PR_BODY(FULL) });
  assert.strictEqual(done(w, gh), 0, w.err);
  const body = posts(gh)[0][2].body;
  assert.ok(body.startsWith("DONE T-1: merged as stella-rain/core#652 (681319e): Fix the thing\n"), body);
  assert.ok(body.includes("**NOT VERIFIED**\n- cargo bench: no runner"));
  assert.ok(body.includes("**Kade's steps**\n- [ ] merge it\n- [x] ran it"));
  assert.ok(body.includes("**Follow-ups**\n- rules text for .claude/rules/simulation.md and more\n- restore_removed_fields"));
  assert.ok(!body.includes("Parse errors"));
  assert.ok(body.endsWith("**Placeholders:** none." + FOOTER));
  assert.deepStrictEqual(gh.writes().slice(1).map((x) => x.slice(0, 2)),
    [["DELETE", Q + "/586/labels/status%3Arunning"], ["PATCH", Q + "/586"]]);
  assert.deepStrictEqual(gh.writes()[2][2], { state: "closed", state_reason: "completed" });
  assert.match(w.ignoreLines().at(-1), new RegExp(`^${ISO} close stella-rain/tasks#586$`));
});

test("done: empty sections are left out; placeholders are listed", () => {
  const w = world();
  let gh = doneGh();
  done(w, gh);
  for (const h of ["NOT VERIFIED", "Kade's steps", "Follow-ups"]) assert.ok(!posts(gh)[0][2].body.includes(`**${h}**`), h);
  gh = doneGh({ body: PR_BODY({ ph: "- a = 1" }) });
  done(w, gh);
  assert.ok(posts(gh)[0][2].body.includes("**Placeholders**\n- a = 1"));
  assert.ok(!posts(gh)[0][2].body.includes("Placeholders:** none"));
});

