// --- dry run ---

test("--dry-run: reads run, each write is shown as `would`, nothing sent and no ignore file", () => {
  const cases = [
    [["dispatched", "586", "T-1", "s"], () => fakeGh({ [Q + "/586"]: issue(["status:approved"]) })],
    [["label", "586", "held"], () => fakeGh({ [Q + "/586"]: issue(["status:approved"]) })],
    [["done", "586", "stella-rain/core#652", "--route", "574"], () => doneGh({ body: PR_BODY(FULL) })],
  ];
  for (const [argv, make] of cases) {
    const w = world();
    const gh = make();
    assert.strictEqual(w.run(["--dry-run", ...ORG, ...argv], gh), 0, w.err);
    assert.ok(w.out.startsWith("would "), w.out);
    assert.deepStrictEqual(gh.writes(), []);
    assert.ok(gh.calls.length > 0);
    assert.ok(!fs.existsSync(w.ign));
  }
  const w = world();
  assert.strictEqual(w.run(["--dry-run", ...ORG, "decision", "DS-0548", w.file("**DS-0548 · 2026-11-11 · Kade:** x")], fakeGh()), 0);
  assert.ok(w.out.startsWith("would POST"));
});
